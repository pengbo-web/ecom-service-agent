/**
 * 计数的显示口径:**数据还没到 ≠ 数量是 0。**
 *
 * **实测缺陷**(前端体验时抓到)。打开「我的订单」,加载要 ~3 秒,而这期间标题
 * 一直写着「0 笔」——买家看到的是"我没有订单",而他其实有两笔。等数据到了数字
 * 才跳成 2。
 *
 * 全仓这个形态有 6 处(`{x?.length ?? 0}`):我的订单、协作链、跨线异常、
 * 现行技能、待审候选、活跃灰度。都是同一句话说了两件事:
 *
 *     null  → 还不知道
 *     0     → 确实没有
 *
 * 用 `?? 0` 把前者压成后者,等于**在自己都还不知道的时候先给一个确定的答案**。
 * 这和本仓库反复守的那条纪律是同一条:`/api/products` 失败时不能返回空列表冒充
 * "这家店没有商品";购物车取不到价格时给 `null` 而不是 0,因为「¥0」会被买家当真。
 *
 * 破折号是刻意的:它读起来就是"还没有值",不会被误读成任何数量。
 */

/** 计数徽标的文本。`null`/`undefined` → `—`(未知),数字 → 原样。 */
export function countLabel(n: number | null | undefined): string {
  return n == null ? "—" : String(n);
}
