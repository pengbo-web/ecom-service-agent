"""出话金钱承诺检测:回复里许了钱,而这一轮没有政策依据。

**实测缺陷。** 买家问的是尺码,客服顺口答了一句:

    「…如不合适可免费换货（支持7天无理由，平台承担换货运费）」

而平台真实政策是"若已签收且属七天无理由退货,**运费由您承担**(约12元起)"——
方向相反。这是一个**对客的金钱承诺**,且与政策矛盾。

为什么既有的三道防线都没挡住:

1. `app/prompts/agents.py` 有硬规则"涉及费用必须先检索知识库"——但它只在模型
   **自认为在讲政策**时才起作用。买家问的是尺码,模型是顺口带出来的。
2. `COMMITMENT_KEYWORDS`(app/agent/skills/risk.py)这份词表存在,但只用在 skill
   风险分级、触达草稿、评价关键词三处——**买家回复这条路上一个金钱承诺检查都没有**。
3. 即便用上,朴素子串匹配也会漏:词表里是 `承担运费`,回复写的是"承担**换货**运费",
   中间插了一个词就匹配不上。

第 3 点尤其值得记:`growth.py` 里那段注释解释过为什么当时能接受朴素匹配——

    "这个残余漏洞是可接受的,因为每条草稿都必须经人工审批才会发出"

**这个理由在买家回复上不成立。** 同一份词表挪到一条没有人工闸的路径上,宽松度
必须重新评估;把一个缓解措施连同它的前提一起搬走,是这类问题的常见成因。

---

**本模块只检测,不阻断、不改写**(与 `jargon_guard` 同姿态)。理由:改写一句已经
生成好的回复很容易把它弄坏(把"运费由您承担"误改成别的意思比原来更糟),而拦掉整条
回复意味着买家什么都收不到。先让"发生过"可观测、可度量,拦不拦是下一阶段的决策。

判定用两个信号的**合取**:说了钱 **且** 这一轮没有平台知识依据。只看第一个会把
"检索到政策后如实转述运费规则"这种正确行为也标出来——那是噪音,而噪音会让这道
检测很快被忽略。
"""

from __future__ import annotations

import re

# 金钱承诺的宽松匹配。**不复用 skills.risk 那份朴素子串表**,而是在它的语义基础上
# 允许中间插词——那正是实测漏掉"承担换货运费"的原因。
#
# 每条都写成"动作 + 最多若干字 + 钱/费用"的形态,`.{0,6}` 是刻意给的窄窗口:
# 开太宽会把"运费由您承担"(如实转述政策,不是承诺)也匹配进来。
#: 承担方是"店铺这一侧"才算承诺。**这个区分是必须的**:"运费由您承担"是如实转述
#: 平台政策(正确行为),"运费由平台承担"是对客金钱承诺——两句话结构几乎一样,差别
#: 只在主语。不区分就会把正确行为也标出来,而噪音会让这道检测很快被忽略。
_SHOP_SIDE = r"(?:平台|我们|商家|店铺|本店|小夕)"
_FEE = r"(?:运费|邮费|快递费)"
_BEAR = r"(?:承担|负担|承付)"

_COMMITMENT_PATTERNS: tuple[tuple[str, str], ...] = (
    # 两种语序都要覆盖:"平台承担换货运费"(动作在前)与"运费由平台承担"(费用在前)。
    # 只写前一种是不够的——这条是被自己的测试抓出来的。
    ("承担运费",
     rf"{_SHOP_SIDE}.{{0,4}}{_BEAR}.{{0,6}}{_FEE}"
     rf"|{_FEE}.{{0,4}}由.{{0,3}}{_SHOP_SIDE}.{{0,4}}{_BEAR}"),
    ("免运费", r"(?:免运费|免邮|包邮|运费全免)"),
    ("免费换退", r"免费(?:换货|退货|上门取件)"),
    ("赔付补偿", r"(?:赔付|先行赔付|补偿|返现|退差价)"),
    ("全额退", r"(?:全额退款|全额退|无条件退)"),
    ("补券", r"(?:补发|赠送|额外给).{0,4}(?:优惠券|代金券|券)"),
)
_COMPILED = [(name, re.compile(pat)) for name, pat in _COMMITMENT_PATTERNS]


def find_commitments(reply_text: str) -> list[str]:
    """回复里命中的金钱承诺类别(去重,保持词表顺序)。无命中返回 []。"""
    text = reply_text or ""
    if not text:
        return []
    return [name for name, rx in _COMPILED if rx.search(text)]


def detect_unbacked_commitment(reply_text: str, kb_grounded: bool) -> list[str]:
    """许了钱**且**这一轮没有平台知识依据 → 返回命中的类别;否则 []。

    `kb_grounded`:本轮是否真的拿到了平台知识(KB 预召回有命中,或调用了
    search_knowledge 并有结果)。检索到政策后如实转述运费规则是**正确行为**,
    不该被标出来——那是噪音,而噪音会让这道检测很快被忽略。
    """
    if kb_grounded:
        return []
    return find_commitments(reply_text)
